/* YC&AC Pulse — pure league-form helpers over the published Division 3 feed
   (fixtures.js, generated by npm run update:fixtures). The match page reads
   both clubs' recent results, records, runs and next fixtures from here so
   the logic stays testable (tests/unit/league.test.cjs) and match.js only
   formats. Names are matched on norm() — "YC&AC Pulse", "YCAC Pulse" and the
   feed's own spelling are the same club, "F. Lions FC" == "F Lions FC". */
(() => {
  const norm = (name) => String(name || "").toLowerCase().replace(/[^a-z0-9]+/g, "");

  // One feed row from `club`'s side: who they met, the score in their order.
  const perspective = (row, club) => {
    const key = norm(club);
    const home = norm(row.home) === key;
    if (!home && norm(row.away) !== key) return null;
    const gf = home ? row.hg : row.ag;
    const ga = home ? row.ag : row.hg;
    return {
      date: row.date,
      opponent: home ? row.away : row.home,
      home,
      gf,
      ga,
      outcome: gf > ga ? "win" : gf < ga ? "loss" : "draw",
      scorers: (row.scorers && (home ? row.scorers.home : row.scorers.away)) || [],
    };
  };

  /* Played results through `through` (inclusive; null = all), oldest first so
     the form pills read left → right, then capped to the last `limit`.
     Reviews pass the match date — a result that came later must not leak in. */
  const resultsFor = (feed, club, { through = null, limit = 5 } = {}) => {
    const rows = ((feed && feed.results) || [])
      .map((row) => perspective(row, club))
      .filter((row) => row && (!through || row.date <= through))
      .sort((a, b) => a.date.localeCompare(b.date));
    return rows.length > limit ? rows.slice(rows.length - limit) : rows;
  };

  // W-D-L and goals over a row list (recordLine / stat cells read this).
  const recordOf = (rows) => rows.reduce((acc, row) => {
    acc.p += 1;
    acc[row.outcome === "win" ? "w" : row.outcome === "draw" ? "d" : "l"] += 1;
    acc.gf += row.gf;
    acc.ga += row.ga;
    return acc;
  }, { p: 0, w: 0, d: 0, l: 0, gf: 0, ga: 0 });

  // The run ending at the newest result, e.g. { outcome: "win", length: 2 }.
  const streakOf = (rows) => {
    if (!rows || !rows.length) return null;
    const outcome = rows[rows.length - 1].outcome;
    let length = 0;
    for (let i = rows.length - 1; i >= 0 && rows[i].outcome === outcome; i--) length += 1;
    return { outcome, length };
  };

  /* Wave 37 — how a club's goals are spread across its published league
     results: buckets [0, 1, 2, 3+] count the games in which they scored that
     many. The forecast renders it next to the league table for both clubs, so
     it deliberately ignores `limit` — a spread is a season view, not a form
     strip. `through` behaves exactly like resultsFor's (a review never sees
     what came later). */
  const scoreSpread = (feed, club, { through = null } = {}) => {
    const rows = resultsFor(feed, club, { through, limit: Number.MAX_SAFE_INTEGER });
    const buckets = [0, 0, 0, 0];
    for (const row of rows) buckets[Math.min(row.gf, 3)] += 1;
    return { games: rows.length, buckets };
  };

  /* Upcoming fixtures from `from` (inclusive), soonest first. `skip` drops the
     page's own fixture — { date, opponent } evaluated from this club's side,
     so both columns can exclude the same match. */
  const fixturesFor = (feed, club, { from = null, limit = 3, skip = null } = {}) => {
    const key = norm(club);
    return ((feed && feed.fixtures) || [])
      .map((row) => {
        const home = norm(row.home) === key;
        if (!home && norm(row.away) !== key) return null;
        return { date: row.date, opponent: home ? row.away : row.home, home, kickoff: row.time || null, venue: row.venue || "" };
      })
      .filter((row) => row
        && (!from || row.date >= from)
        && !(skip && row.date === skip.date && norm(row.opponent) === norm(skip.opponent)))
      .sort((a, b) => a.date.localeCompare(b.date))
      .slice(0, limit);
  };

  const api = { norm, perspective, resultsFor, recordOf, streakOf, scoreSpread, fixturesFor };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  if (typeof window !== "undefined") window.YCACLeague = api;
})();
